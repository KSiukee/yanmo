//! 大纲冲突检测：**只报告，绝不自动改稿**。
//!
//! 这一层回答一个问题：作者记下的大纲（设定卡 + 场景卡四格）**自己跟自己对不对得上**。
//! 它不碰正文、不改任何东西、也不判断"这样写好还是不好"——只是把对不上的地方列出来，
//! 让作者自己决定。
//!
//! # 为什么规则版先做，且只做判得动的
//!
//! 判"正文里写的和设定对不上"（人物卡说左手剑、正文写右手）要**实体抽取**，
//! 那是另一件事（这一版不做）。硬做只会变成一堆**猜出来的**问题——
//! 假警报比不报更糟：作者看两次就再也不看了。
//!
//! 所以第一刀只做**机械可判**的四条，全部只依赖结构化数据：
//!
//! | 规则 | 判据 | 数据 |
//! |---|---|---|
//! | `IssueRule::EntityNameClash` | 两张卡共用一个称呼（名字或别称） | 设定卡 |
//! | `IssueRule::EntityNameRepeated` | 同一张卡里同一个称呼登记了两遍 | 设定卡 |
//! | `IssueRule::EntityAttributeConflict` | 同一张卡里同一个属性键给了两个不同的值 | 设定卡 |
//! | `IssueRule::SceneMissingFields` | 场景卡的四格缺了哪几格 | 场景卡 |
//!
//! # 三条纪律
//!
//! 1. **零文案**：产出的是**码 + 参数 + 定位锚点**（句子由界面按字典渲染），
//!    所以这一层能单测、能被命令行驱动、也不把中文塞进数据；
//! 2. **纯逻辑**：规则只吃值（`OutlineData`），不碰库——读数据在 `store::outline_scan`；
//! 3. **每条问题的身份是"规则 + 位置 + 主体"**（`OutlineIssue::fingerprint`）：
//!    作者忽略过的那一条，下一轮照样不同一条新的；而"同一张卡的另一个属性又冲突了"
//!    依然会报（身份里带着属性键）。

