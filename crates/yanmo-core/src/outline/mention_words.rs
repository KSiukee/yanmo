#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;

    /// 两个表**一个都不许重叠**：既当"虚词/量词"又当"姓"的字，会让姓名帧认不出它——
    /// 那个字左边被当成断点，`张三说` 这种句子直接跳过（**踩过一次**：张 曾 万 莫 向）。
    #[test]
    fn a_surname_is_never_a_boundary_word() {
        let overlap: String = SURNAMES.chars().filter(|ch| BOUNDARY.contains(*ch)).collect();
        assert!(overlap.is_empty(), "这些字既是姓又当边界词，姓名帧会认不出它们：{overlap}");
    }

    /// 表里不许有重复：重复只会让"这张表里到底有没有它"更难读。
    #[test]
    fn the_tables_have_no_duplicates() {
        for (name, table) in [
            ("PLACE_SUFFIXES", PLACE_SUFFIXES),
            ("SURNAMES", SURNAMES),
            ("BOUNDARY", BOUNDARY),
            ("BAD_LONE_PREFIX", BAD_LONE_PREFIX),
        ] {
            let mut seen = BTreeSet::new();
            let duplicated: String = table.chars().filter(|ch| !seen.insert(*ch)).collect();
            assert!(duplicated.is_empty(), "{name} 里有重复：{duplicated}");
        }
        let mut seen = BTreeSet::new();
        let duplicated: Vec<&&str> = PERSON_TITLES.iter().filter(|title| !seen.insert(**title)).collect();
        assert!(duplicated.is_empty(), "PERSON_TITLES 里有重复：{duplicated:?}");
        let mut seen_marker = BTreeSet::new();
        let duplicated: Vec<&&str> = ACTION_MARKERS.iter().filter(|m| !seen_marker.insert(**m)).collect();
        assert!(duplicated.is_empty(), "ACTION_MARKERS 里有重复：{duplicated:?}");
    }

    /// 称谓表里不该出现"名字的一部分"：`大` 这种修饰字不该被当成称谓的词头。
    #[test]
    fn the_titles_are_whole_forms() {
        for title in PERSON_TITLES {
            assert!(title.chars().count() >= 2, "单字称谓噪声太大，不收：{title}");
        }
    }
}
