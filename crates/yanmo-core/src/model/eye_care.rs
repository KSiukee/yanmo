//! 护眼滤色：**整窗一层暖黄的膜**，幅度可调（0~100）。
//!
//! 它是作者的偏好（存 `appearance.eye_care`，跟人不跟书），不是数据的属性：
//! 这一层只改屏幕观感，正文、导出与落盘字节一个都不动（有验收钉着）。
//!
//! # 三条口径
//!
//! 1. **只走全局**：跟眼睛与房间光线有关，跟哪本书无关（与配色、用眼提醒同一条口径）——
//!    所以它不参与每书覆盖，写也只在全局那一层落库。
//! 2. **0 是正经取值（＝关）**：界面把滑杆拉到最左边就是 0，那一下要**一个像素都不染**
//!    （不是"画一层透明的"）。默认也是 0：不给没提过这件事的人换底子。
//! 3. **越界夹住，不报错**：它是纯观感（与正文排版那三项同一条路）——手滑写个离谱的数
//!    不该把设置面板挡在外面。
//!
//! # 为什么这里只存"多少"，不存"那层膜到底多深"
//!
//! 那层膜压在**什么底**上，只有界面当场知道（浅色稿纸还是深色暖黑）。深色底下再压一层
//! 强黄会把明暗两头一起吃掉（白字发灰、黑底发黄，糊成一团），所以界面要拿当前配色
//! **合计**出一个上限（见 `frontend/src/editor/eye-care.ts`）。核心存一份算好的深度就会
//! 腐烂：作者一换配色，这边还记着上一次算出的那个数。
//!
//! # 边界：只染研墨自己的窗口
//!
//! 整机滤色**不做**——要么改系统设置 / 注册表（副作用，还可能提权），要么往别的进程注入
//! （绝不做）。想要整机滤色的人，系统自带的夜间模式就是他要的东西（设置面板里写着这句话）。

/// 护眼滤色的幅度上限（百分比）。100 ＝ 滑杆拉到最右。
pub const MAX_EYE_CARE: i64 = 100;

/// 默认幅度：**关**（0）——不给没提过这件事的人换底子（与配色默认浅色同一条分寸）。
pub const DEFAULT_EYE_CARE: i64 = 0;

#[cfg(test)]
mod tests {
    use super::*;

    /// 默认必须是"完全不染"：新库出生时屏幕上与一直以来的样子一模一样。
    #[test]
    fn the_default_is_off_and_the_range_starts_at_off() {
        assert_eq!(DEFAULT_EYE_CARE, 0, "默认关：没提过这件事的人不该看到一层黄");
        assert!(MAX_EYE_CARE > DEFAULT_EYE_CARE, "上限得比默认大，否则滑杆拉不动");
    }
}
